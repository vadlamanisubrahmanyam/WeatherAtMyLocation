#!/usr/bin/env node
/**
 * Inlines web/index.html + its local CSS/JS into src/weatherHtml.ts so the WebView
 * can load the whole app from a single string (no file-asset plumbing needed).
 *
 *   node scripts/embed-html.js
 *
 * Edit the files in web/, then re-run this script. During development you can also
 * open web/index.html directly in a browser.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const webDir = path.join(root, 'web');
let html = fs.readFileSync(path.join(webDir, 'index.html'), 'utf8');

html = html.replace(/<link rel="stylesheet" href="([^":]+)">/g, (_, file) =>
  `<style>\n${fs.readFileSync(path.join(webDir, file), 'utf8')}\n</style>`);
html = html.replace(/<script src="([^":]+)"><\/script>/g, (_, file) => {
  const js = fs.readFileSync(path.join(webDir, file), 'utf8');
  if (/<\/script/i.test(js)) throw new Error(`${file} contains "</script" and cannot be inlined`);
  return `<script>\n${js}\n</script>`;
});

const out = `// AUTO-GENERATED by scripts/embed-html.js from web/ — do not edit by hand.\n` +
  `const WEATHER_HTML: string = ${JSON.stringify(html)};\nexport default WEATHER_HTML;\n`;
fs.mkdirSync(path.join(root, 'src'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'weatherHtml.ts'), out);
console.log(`src/weatherHtml.ts written (${(out.length / 1024).toFixed(0)} KB)`);
